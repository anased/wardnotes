// src/lib/articles/note.ts
// Turn an article's primer and guide into a WardNotes summary note (TipTap JSON) and
// flashcards. Pure; client-safe.
import { STUDY_KIND_LABELS, pubmedUrl, type ArticleRead, type GuideContent } from './types';

type TextNode = { type: 'text'; text: string; marks?: { type: string; attrs?: Record<string, string> }[] };
type Node = { type: string; attrs?: Record<string, unknown>; content?: (Node | TextNode)[] };

const text = (t: string, marks?: TextNode['marks']): TextNode => (marks ? { type: 'text', text: t, marks } : { type: 'text', text: t });
const bold = (t: string) => text(t, [{ type: 'bold' }]);
const link = (t: string, href: string) => text(t, [{ type: 'link', attrs: { href, target: '_blank' } }]);
const paragraph = (...content: TextNode[]): Node => ({ type: 'paragraph', content });
const heading = (t: string): Node => ({ type: 'heading', attrs: { level: 2 }, content: [text(t)] });
const bullets = (items: TextNode[][]): Node => ({
  type: 'bulletList',
  content: items.map((content) => ({ type: 'listItem', content: [paragraph(...content)] })),
});

const BIAS_LABELS = { low: 'Low', some_concerns: 'Some concerns', high: 'High' } as const;

/** The note body: primer, key numbers, appraisal and a link back to the source. */
export function buildSummaryNoteContent(article: ArticleRead, guide: GuideContent | null): Node {
  const content: Node[] = [];
  const source = [STUDY_KIND_LABELS[article.study_kind], article.journal, article.year].filter(Boolean).join(' · ');
  content.push(paragraph(text(source)));

  const primer = article.primer;
  if (primer) {
    if (primer.question) content.push(heading('Question'), paragraph(text(primer.question)));
    content.push(heading('Bottom line'), paragraph(text(primer.bottomLine)));
  }

  if (guide?.stats.length) {
    content.push(
      heading('Key numbers'),
      bullets(guide.stats.map((s) => [bold(`${s.label}: `), text(`${s.value}. ${s.meaning}`)]))
    );
  }

  if (guide) {
    const { strengths, weaknesses, biasRisk, biasReason } = guide.appraisal;
    if (strengths.length || weaknesses.length) {
      content.push(heading('Appraisal'));
      if (strengths.length) content.push(paragraph(bold('Strengths')), bullets(strengths.map((p) => [text(p.text)])));
      if (weaknesses.length) content.push(paragraph(bold('Weaknesses')), bullets(weaknesses.map((p) => [text(p.text)])));
    }
    content.push(paragraph(bold('Risk of bias: '), text(`${BIAS_LABELS[biasRisk]}${biasReason ? `. ${biasReason}` : ''}`)));
  }

  const links: TextNode[] = [bold('Source: ')];
  if (article.pmid) links.push(link(`PubMed ${article.pmid}`, pubmedUrl(article.pmid)));
  if (article.doi) {
    if (article.pmid) links.push(text(' · '));
    links.push(link(`doi:${article.doi}`, `https://doi.org/${article.doi}`));
  }
  if (links.length > 1) content.push(paragraph(...links));
  content.push(paragraph(text('Summary generated by Deep Read from the article; numbers were checked against the source.')));

  return { type: 'doc', content };
}

export interface CardDraft {
  front: string;
  back: string;
}

/** Front/back cards from the guide's Q&A and quiz (no AI needed). */
export function guideToCards(guide: GuideContent): CardDraft[] {
  const cards: CardDraft[] = [
    ...guide.qa.map((q) => ({ front: q.question, back: q.answer })),
    ...guide.quiz.map((q) => ({
      front: q.question,
      back: [q.options[q.answerIndex], q.explanation].filter(Boolean).join('\n\n'),
    })),
  ];
  const seen = new Set<string>();
  return cards.filter((c) => {
    const key = c.front.trim().toLowerCase();
    if (!c.front.trim() || !c.back.trim() || seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}
